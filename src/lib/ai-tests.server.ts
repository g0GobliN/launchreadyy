// Post-process the raw AI response for a todo-markers fix:
// 1. Strip any markdown fences + explanation text the model added despite instructions.
// 2. Reject if the result lost >40% of the original lines (model deleted the file).
// 3. Reject if the result still starts with non-code prose.
function cleanTodoFixOutput(raw: string, original: string, actualLineCount = 0): string | null {
  let text = raw;

  // Strip markdown fences (```ts ... ``` or plain ```)
  const fenceRe = /^```[a-z]*\n/m;
  const fenceMatch = text.match(fenceRe);
  if (fenceMatch?.index !== undefined) {
    const afterFence = text.slice(fenceMatch.index + fenceMatch[0].length);
    const closingIdx = afterFence.lastIndexOf("\n```");
    if (closingIdx !== -1) {
      text = afterFence.slice(0, closingIdx);
    }
  }

  // Strip any leading prose lines before the first code line
  const codeLineRe =
    /^(import |export |const |let |var |function |class |interface |type |\/\/|\/\*|# |from |package |use |pub |fn |def |module |@[a-zA-Z]|<[a-zA-Z])/m;
  const codeStart = text.match(codeLineRe);
  if (codeStart?.index !== undefined && codeStart.index > 0) {
    text = text.slice(codeStart.index);
  }

  text = text.trimEnd() + "\n";

  // Reject if the model deleted most of the file.
  // Use the larger of (passed original, stored actual) so truncated inputs don't fool the guard.
  const originalLineCount = Math.max(original.split("\n").length, actualLineCount);
  const resultLineCount = text.split("\n").length;
  if (resultLineCount < originalLineCount * 0.6) return null;

  return text;
}

export interface AiTestFile {
  fixId: string;
  path: string;
  content: string;
}

// bypassCache: set to true when the user explicitly requested a new attempt (regenerate flow) —
// always hits the AI fresh, never reads from or writes to the shared cache, so a re-run without
// feedback doesn't silently return the same output the user already rejected, and feedback-steered
// results don't pollute the cache for other users.
export async function generateAiTests(
  scanId: string,
  fixIds: string[],
  fullName: string,
  token: string,
  framework?: string,
  feedback?: string,
  bypassCache = false,
): Promise<AiTestFile[]> {
  const db = getDataStore();
  const sortedKey = [...fixIds].sort().join(",");
  const skipCache = bypassCache || !!feedback;

  if (!skipCache) {
    const { data: scanCached } = await db
      .from("ai_test_cache")
      .select("result")
      .eq("scan_id", scanId)
      .eq("fix_ids", sortedKey)
      .eq("prompt_version", PROMPT_VERSION)
      .maybeSingle();
    if (scanCached) return JSON.parse(scanCached.result) as AiTestFile[];
  }

  const repoUrl = `https://github.com/${fullName}`;
  const relevantFiles = await fetchRelevantFiles(token, fullName, fixIds, framework);
  const contentHash = hashFiles(relevantFiles, fixIds);

  if (!skipCache) {
    const { data: hashCached } = await db
      .from("ai_test_cache")
      .select("result")
      .eq("content_hash", contentHash)
      .eq("prompt_version", PROMPT_VERSION)
      .maybeSingle();
    if (hashCached) {
      await db.from("ai_test_cache").insert({
        id: crypto.randomUUID(),
        scan_id: scanId,
        fix_ids: sortedKey,
        result: hashCached.result,
        content_hash: contentHash,
        prompt_version: PROMPT_VERSION,
      });
      return JSON.parse(hashCached.result) as AiTestFile[];
    }
  }

  const results: AiTestFile[] = [];

  // Phase 2 knowledge read path — inject into single-shot AI fixes (not only multi-agent).
  let repoKnowledge = "";
  try {
    const { data: scanRow } = await db
      .from("scans")
      .select("repo_id")
      .eq("id", scanId)
      .maybeSingle();
    if (scanRow?.repo_id) {
      const { loadRepoKnowledgeContext } = await import("./knowledge/writer.server");
      repoKnowledge = await loadRepoKnowledgeContext(scanRow.repo_id);
    }
  } catch (e) {
    console.error("[ai-tests] repo knowledge load failed:", e);
  }

  for (const fixId of fixIds) {
    if (fixId === "auditor-todo-markers") {
      // Generate a TODO_REPORT.md — a safe, additive new file that consolidates all markers.
      // We do NOT edit existing source files: AI surgical edits are unreliable and risky.
      let todoFilePaths: string[] = [];
      try {
        todoFilePaths = JSON.parse(relevantFiles["__todo_files"] ?? "[]");
      } catch {
        todoFilePaths = [];
      }
      if (todoFilePaths.length === 0) continue;

      // Build a compact context block: file path + the comment lines that contain markers
      const TODO_COMMENT_RE =
        /^\s*(?:\/\/|#|\*|\/\*).*\b(TODO|FIXME|HACK|XXX|PLACEHOLDER|not\s+implemented|coming\s+soon)\b/im;
      const sections: string[] = [];
      for (const filePath of todoFilePaths) {
        const content = relevantFiles[filePath];
        if (!content) continue;
        const markerLines = content
          .split("\n")
          .map((line, i) => ({ line, n: i + 1 }))
          .filter(({ line }) => TODO_COMMENT_RE.test(line))
          .map(({ line, n }) => `  L${n}: ${line.trim()}`)
          .slice(0, 10)
          .join("\n");
        if (markerLines) sections.push(`### ${filePath}\n${markerLines}`);
      }

      const prompt = `You are a senior developer creating a structured TODO report for a ${framework ?? "TypeScript"} project.

Below are the incomplete implementation markers found across the codebase. Write a markdown file called TODO_REPORT.md that:
1. Has a short intro explaining these were found by an automated scan
2. Groups entries by file with a header for each file
3. For each marker line, writes: the line number, the original comment, and a one-sentence recommendation (implement it, delete it if stale, or link it to a ticket)
4. Ends with a "Next steps" section

Do NOT modify any source files. Output ONLY the markdown content. No code fences around the whole document.

${sections.join("\n\n")}`;

      const text = await aiService.generate(prompt, { taskType: "code", maxTokens: 3072, repoUrl });
      results.push({
        fixId,
        path: "TODO_REPORT.md",
        content: stripCodeFence(text).trimEnd() + "\n",
      });
      continue;
    }

    // These auditor fixes only make sense against a concrete file the scanner actually found
    // (a real route, a real protected page, a real Prisma schema). Without one, the model has
    // nothing grounded to patch and fabricates a generic, sometimes-invalid file instead — so
    // skip cleanly (same pattern as auditor-todo-markers above) rather than shipping a guess.
    if (
      (fixId === "auditor-api-validation" ||
        fixId === "auditor-auth-routes" ||
        fixId === "auditor-localhost-api") &&
      !relevantFiles["__auditor_target"]
    ) {
      continue;
    }
    if (fixId === "auditor-prisma-migrations" && !relevantFiles["prisma/schema.prisma"]) {
      continue;
    }

    if (fixId === "ci-ai" && shouldUseDeterministicCi(relevantFiles)) {
      const content = buildDeterministicCiWorkflow(relevantFiles, {
        framework,
        fixIds,
      });
      results.push({ fixId, path: outputPath(fixId, relevantFiles), content });
      continue;
    }

    const prompt = buildPrompt(fixId, relevantFiles, repoUrl, framework, feedback, repoKnowledge);
    const taskType = taskTypeForFix(fixId);
    // readme-ai gets a much bigger budget — it must reproduce the entire existing README verbatim
    // plus additions, not just author a short new file like ci.yml/.env.example. The test fixes
    // (vitest/playwright/api-tests) now get several real source files instead of one, so they
    // need more room to write coverage for all of them, not just the first.
    const maxTokens =
      fixId === "readme-ai"
        ? 6144
        : fixId === "ci-ai"
          ? 2560
          : fixId === "env-example-ai"
            ? 1536
            : [
                  "vitest-ai",
                  "playwright-ai",
                  "api-tests",
                  "pytest-ai",
                  "go-test-ai",
                  "rspec-ai",
                  "phpunit-ai",
                  "junit-ai",
                  "cargo-test-ai",
                  "xunit-ai",
                  "exunit-ai",
                  "dart-test-ai",
                  "swift-test-ai",
                  "kotlin-test-ai",
                ].includes(fixId)
              ? 3072
              : isAuditorFixId(fixId)
                ? 3072
                : 2048;
    // Empirically, the model occasionally returns empty content for a given prompt (seen on
    // reasoning-model routes where the reasoning phase can consume the response with nothing
    // left over) even though a retry with the identical prompt succeeds — so retry once before
    // giving up rather than showing the user a blank file.
    let text = await aiService.generate(prompt, { taskType, maxTokens, repoUrl });
    if (!text.trim()) {
      text = await aiService.generate(prompt, { taskType, maxTokens, repoUrl });
    }
    const outPath = outputPath(fixId, relevantFiles);
    text = stripEchoedOutputPath(text, outPath);
    let content =
      fixId === "ci-ai" ? finalizeCiWorkflow(text) : stripCodeFence(text).trimEnd() + "\n";

    // On large/complex repos the model sometimes runs out of budget mid-file (seen: a test
    // file cut off mid-word). One retry with a bigger budget resolves it without inflating
    // cost for the common case where the first attempt already fits comfortably.
    if (validateGeneratedFile(outPath, content).status === "invalid") {
      // The router's response cache keys on (provider, model, method, prompt) — not maxTokens —
      // so reusing the identical prompt here would just return the same truncated text back out
      // of cache instead of making a fresh call with more room. Force a cache bypass.
      const retryText = await aiService.generate(prompt, {
        taskType,
        maxTokens: Math.round(maxTokens * 2.2),
        repoUrl,
        cacheKey: `retry:${crypto.randomUUID()}`,
      });
      const strippedRetry = stripEchoedOutputPath(retryText, outPath);
      const retryContent =
        fixId === "ci-ai"
          ? finalizeCiWorkflow(strippedRetry)
          : stripCodeFence(strippedRetry).trimEnd() + "\n";
      if (validateGeneratedFile(outPath, retryContent).status !== "invalid") {
        content = retryContent;
      }
    }
    results.push({ fixId, path: outPath, content });
  }

  if (!skipCache) {
    await db.from("ai_test_cache").insert({
      id: crypto.randomUUID(),
      scan_id: scanId,
      fix_ids: sortedKey,
      result: JSON.stringify(results),
      content_hash: contentHash,
      prompt_version: PROMPT_VERSION,
    });
  }

  return results;
}

export async function hasAiTestCache(
  scanId: string,
  fixIds: string[],
  fullName?: string,
  token?: string,
  framework?: string,
): Promise<boolean> {
  if (fixIds.length === 0) return false;
  const db = getDataStore();
  const sortedKey = [...fixIds].sort().join(",");

  const { data: scanHit } = await db
    .from("ai_test_cache")
    .select("id")
    .eq("scan_id", scanId)
    .eq("fix_ids", sortedKey)
    .maybeSingle();
  if (scanHit) return true;

  if (fullName && token) {
    const relevantFiles = await fetchRelevantFiles(token, fullName, fixIds, framework);
    const contentHash = hashFiles(relevantFiles, fixIds);
    const { data: hashHit } = await db
      .from("ai_test_cache")
      .select("id")
      .eq("content_hash", contentHash)
      .eq("prompt_version", PROMPT_VERSION)
      .maybeSingle();
    if (hashHit) return true;
  }

  return false;
}
