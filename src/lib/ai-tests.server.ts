function hashFiles(files: Record<string, string>, fixIds: string[]): string {
  // Include active provider + model env vars so a model upgrade busts cached outputs
  // generated by the previous model — users get the better quality immediately.
  const modelKey = [
    process.env.AI_PROVIDER ?? "deepseek",
    process.env.DEEPSEEK_MODEL ?? "deepseek-chat",
    process.env.DEEPSEEK_REASONER_MODEL ?? "deepseek-reasoner",
    process.env.CLAUDE_MODEL ?? "claude-sonnet-4-6",
    process.env.CLAUDE_FAST_MODEL ?? "claude-haiku-4-5-20251001",
    process.env.CLAUDE_OPUS_MODEL ?? "claude-opus-4-8",
  ].join(":");
  const stable =
    PROMPT_VERSION +
    modelKey +
    [...fixIds].sort().join(",") +
    JSON.stringify(Object.entries(files).sort());
  return createHash("sha256").update(stable).digest("hex");
}

