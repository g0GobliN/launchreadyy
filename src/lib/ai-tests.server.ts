// Detects real external-call patterns (HTTP clients, DB/ORM clients) in the actual source
// samples already gathered — used to tell the model to mock these instead of letting generated
// tests silently hit real networks/databases.
function mockingInstruction(files: Record<string, string>): string {
  const sourceContent = Object.entries(files)
    .filter(([p]) => !p.startsWith("__"))
    .map(([, c]) => c)
    .join("\n");
  const pattern =
    /\bfetch\(|axios\.|\bky\.|\.from\(["'`]|new\s+(Pool|Client)\(|mongoose\.|prisma\.|supabase/;
  if (!pattern.test(sourceContent)) return "";
  return "\n- The source above makes real network/database calls — mock those (vi.mock / vi.fn / msw) so tests don't depend on a live network or database";
}

// Derived from the source of every function that shapes prompt output — editing wording or the
// deterministic facts fed into it changes this hash automatically, invalidating every
// ai_test_cache row written under the old version. No one has to remember to bump it by hand.
const PROMPT_VERSION = createHash("sha256")
  .update(
    buildPrompt.toString() +
      extractReadmeFacts.toString() +
      mockingInstruction.toString() +
      buildDeterministicCiWorkflow.toString() +
      buildProjectContext.toString() +
      projectContextToAiFiles.toString() +
      buildPlaywrightConfig.toString() +
      resolvePlaywrightTarget.toString() +
      resolveWebServerScript.toString() +
      resolveDevScript.toString() +
      playwrightInputFromFiles.toString() +
      "deterministic-ci-ai-v7-intelligence-auditor-fixes-v7-todo-report-cached",
  )
  .digest("hex")
  .slice(0, 12);

