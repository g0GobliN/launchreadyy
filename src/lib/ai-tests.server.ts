const GITHUB_API = "https://api.github.com";
const README_PATHS = ["README.md", "readme.md", "README", "README.markdown", "Readme.md"];

async function ghFetch(token: string, path: string) {
  return fetch(`${GITHUB_API}${path}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github.v3+json",
      "User-Agent": "LaunchReadyy/1.0",
    },
  });
}

async function fetchFileViaContentsApi(
  token: string,
  fullName: string,
  filePath: string,
): Promise<string | null> {
  const res = await ghFetch(token, `/repos/${fullName}/contents/${githubContentsPath(filePath)}`);
  if (!res.ok) return null;
  const data = (await res.json()) as { content?: string; encoding?: string };
  if (!data.content || data.encoding !== "base64") return null;
  return Buffer.from(data.content.replace(/\n/g, ""), "base64").toString("utf-8");
}

async function fetchFile(
  token: string,
  fullName: string,
  filePath: string,
): Promise<string | null> {
  return snapshotFile(token, fullName, filePath, fetchFileViaContentsApi);
}

async function fetchReadme(token: string, fullName: string): Promise<string | null> {
  for (const path of README_PATHS) {
    const content = await fetchFile(token, fullName, path);
    if (content) return content;
  }
  return null;
}

async function fetchTreePaths(token: string, fullName: string): Promise<string[]> {
  try {
    return (await getRepoSnapshot(token, fullName)).filePaths;
  } catch {
    // Tarball unavailable — fall back to the trees API.
  }
  const repoRes = await ghFetch(token, `/repos/${fullName}`);
  if (!repoRes.ok) return [];
  const repo = (await repoRes.json()) as { default_branch?: string };
  const branch = repo.default_branch ?? "main";
  const res = await ghFetch(token, `/repos/${fullName}/git/trees/${branch}?recursive=1`);
  if (!res.ok) return [];
  const data = (await res.json()) as { tree: Array<{ path: string; type: string }> };
  return data.tree.filter((n) => n.type === "blob").map((n) => n.path);
}

const ENV_SCAN_DIRS = ["src", "app", "pages", "lib", "server", "api"];

async function scanEnvVarUsages(
  token: string,
  fullName: string,
  paths: string[],
): Promise<string[]> {
  const vars = new Set<string>();
  const candidates = paths.filter(
    (p) =>
      /\.(ts|tsx|js|jsx|mjs|cjs)$/.test(p) &&
      ENV_SCAN_DIRS.some((d) => p === `${d}` || p.startsWith(`${d}/`)),
  );
  for (const p of candidates.slice(0, 60)) {
    const content = await fetchFile(token, fullName, p);
    if (!content) continue;
    for (const m of content.matchAll(/process\.env\.([A-Z_][A-Z0-9_]*)/g)) vars.add(m[1]);
    for (const m of content.matchAll(/import\.meta\.env\.([A-Z_][A-Z0-9_]*)/g)) vars.add(m[1]);
  }
  return [...vars].sort();
}

// obj/ and bin/ are .NET build output (generated AssemblyInfo.cs etc. — never app logic worth
// sampling); bin/ elsewhere is launcher stubs (bin/rails, bin/setup), equally not app logic.
// migrations/ is generated schema history (EF Core's Migrations/*.Designer.cs snapshots are
// especially huge) — confirmed against the real davidfowl/TodoApi: 6 of xunit-ai's 12 sample
// slots were EF migration files, crowding out the actual endpoint code the model should ground
// tests in. `<Project>.Tests/` is the .NET test-project naming convention (same repo shipped
// Todo.Api.Tests/, invisible to the `tests/` dir rule).
export const NOT_A_SOURCE_SAMPLE =
  /\.(test|spec)\.|\.d\.ts$|(^|\/)(__tests__|tests|e2e|node_modules|obj|bin|migrations)\/|(^|\/)[^/]+\.tests?\//i;

// Fetches the contents of real source files matching `pattern`, picked from the actual repo
// tree — used to ground test generation in real code instead of a single guessed entry point.
async function fetchSourceSamples(
  token: string,
  fullName: string,
  treePaths: string[],
  pattern: RegExp,
  opts: { max?: number; perFileChars?: number } = {},
): Promise<Record<string, string>> {
  const { max = 12, perFileChars = 5000 } = opts;
  const matches = treePaths
    .filter((p) => pattern.test(p) && !NOT_A_SOURCE_SAMPLE.test(p))
    .slice(0, max);
  const out: Record<string, string> = {};
  for (const p of matches) {
    const c = await fetchFile(token, fullName, p);
    if (c) out[p] = c.slice(0, perFileChars);
  }
  return out;
}

/**
 * Picks the pubspec.yaml governing the sampled Dart sources — the package dir containing the
 * most samples wins. Multi-package repos (confirmed real: roughike/inKino has core/+mobile/+web/
 * packages and no root pubspec.yaml) keep the `package:` import name a test file needs in the
 * pubspec sibling to its lib/, not at the repo root.
 */
export function resolveDartPackagePubspec(
  samplePaths: string[],
  treePaths: string[],
): string | null {
  const counts = new Map<string, number>();
  for (const p of samplePaths) {
    const m = p.match(/^(.*\/)?(?:lib|bin)\//);
    if (!m) continue;
    const prefix = m[1] ?? "";
    counts.set(prefix, (counts.get(prefix) ?? 0) + 1);
  }
  const ranked = [...counts.entries()].sort((a, b) => b[1] - a[1]);
  for (const [prefix] of ranked) {
    const candidate = `${prefix}pubspec.yaml`;
    if (treePaths.includes(candidate)) return candidate;
  }
  return null;
}

// Resolves a TS/JS import specifier to a repo-relative path.
// Returns null for bare package imports (no leading . or @/).
function resolveImportPath(
  fromFile: string,
  specifier: string,
  treePaths: string[],
): string | null {
  let base: string;
  if (specifier.startsWith("./") || specifier.startsWith("../")) {
    const dir = fromFile.includes("/") ? fromFile.replace(/\/[^/]+$/, "") : "";
    base = dir ? `${dir}/${specifier}` : specifier;
  } else if (specifier.startsWith("@/")) {
    base = `src/${specifier.slice(2)}`;
  } else {
    return null; // third-party package — skip
  }
  // Normalise /../ segments
  const parts: string[] = [];
  for (const seg of base.split("/")) {
    if (seg === "..") parts.pop();
    else if (seg && seg !== ".") parts.push(seg);
  }
  const normalised = parts.join("/");
  // Try extensions in order — exact match first, then common extensions, then /index.*
  const tries = [
    normalised,
    `${normalised}.ts`,
    `${normalised}.tsx`,
    `${normalised}.js`,
    `${normalised}.jsx`,
    `${normalised}/index.ts`,
    `${normalised}/index.tsx`,
    `${normalised}/index.js`,
  ];
  for (const t of tries) {
    if (treePaths.includes(t)) return t;
  }
  return null;
}

// Starting from seedPaths, follow import statements up to `depth` hops.
// Returns a map of { filePath: content } for all newly discovered files
// (seeds themselves are NOT included — caller already has them).
async function expandWithImportGraph(
  token: string,
  fullName: string,
  seedPaths: string[],
  treePaths: string[],
  opts: { depth?: number; maxExtra?: number } = {},
): Promise<Record<string, string>> {
  const { depth = 2, maxExtra = 20 } = opts;
  const IMPORT_RE = /(?:^|\n)\s*(?:import|export)[^'"]+['"]([^'"]+)['"]/g;
  const extra: Record<string, string> = {};
  const visited = new Set(seedPaths);
  let frontier = [...seedPaths];

  for (let d = 0; d < depth && Object.keys(extra).length < maxExtra; d++) {
    const nextFrontier: string[] = [];
    for (const filePath of frontier) {
      const content = extra[filePath] ?? (await fetchFile(token, fullName, filePath));
      if (!content) continue;
      let m: RegExpExecArray | null;
      IMPORT_RE.lastIndex = 0;
      while ((m = IMPORT_RE.exec(content)) !== null) {
        const resolved = resolveImportPath(filePath, m[1]!, treePaths);
        if (!resolved || visited.has(resolved)) continue;
        visited.add(resolved);
        nextFrontier.push(resolved);
        if (Object.keys(extra).length >= maxExtra) break;
      }
    }
    // Fetch all next-level files in parallel
    await Promise.all(
      nextFrontier.map(async (p) => {
        if (Object.keys(extra).length >= maxExtra) return;
        const c = await fetchFile(token, fullName, p);
        if (c) extra[p] = c;
      }),
    );
    frontier = nextFrontier;
  }
  return extra;
}

// Last-resort fallback when no real source samples matched (e.g. an unconventional layout) —
// grab whichever known entry point exists so the prompt always has at least one real file.
async function fetchFirstExisting(
  token: string,
  fullName: string,
  candidates: string[],
  perFileChars = 3000,
): Promise<{ path: string; content: string } | null> {
  for (const p of candidates) {
    const c = await fetchFile(token, fullName, p);
    if (c) return { path: p, content: c.slice(0, perFileChars) };
  }
  return null;
}

